"""Build-time translation of the fixed 32-point Vorbis x87 butterfly.

Only memory addressing is relocated to checked scratch storage. The opcode and
x87 ModRM operation bits, including subtraction direction, remain unchanged.
"""
from pathlib import Path
import hashlib
import sys

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools/python"))
import capstone
import pefile

raw = (ROOT / "WA2_chs.exe").read_bytes()
assert hashlib.sha256(raw).hexdigest() == "246a263b965147a274fa59cdd7a72f6be10ba063d8cf4e61e74baefb56f29327"
pe = pefile.PE(data=raw)
start, end = 0x46e477, 0x46e95c
code = pe.get_data(start - pe.OPTIONAL_HEADER.ImageBase, end - start)
decoder = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
decoder.detail = True
instructions = list(decoder.disasm(code, start))
assert len(instructions) == 404 and sum(i.size for i in instructions) == len(code)
integer = {
    0x46e48d: "mov ecx, DWORD PTR [r8 + 12]",
    0x46e49a: "mov DWORD PTR [rax + 60], ecx",
    0x46e6a6: "mov edx, DWORD PTR [r8 + 12]",
    0x46e6b3: "mov DWORD PTR [rax + 12], edx",
    0x46e73f: "lea rcx, [rax + 96]",
    0x46e869: "mov edx, DWORD PTR [r8 + 12]",
    0x46e876: "mov DWORD PTR [rax + 76], edx",
    # Scratch [old ESP-4] is initialized to the guest pointer old EAX+96.
    # A native PUSH would store a host pointer and modify the wrong stack.
    0x46e904: "sub r8, 4",
}
body = []
for instruction in instructions:
    body.append(f"    // {instruction.address:#x}: {instruction.mnemonic} {instruction.op_str}")
    if instruction.address in integer:
        body.append("    " + integer[instruction.address])
        continue
    assert 0xd8 <= instruction.bytes[0] <= 0xdf
    encoded = bytes(instruction.bytes)
    memory = [o.mem for o in instruction.operands if o.type == capstone.x86.X86_OP_MEM]
    if memory:
        assert len(memory) == 1
        operand = memory[0]
        assert operand.index == capstone.x86.X86_REG_INVALID
        if operand.base == capstone.x86.X86_REG_ESP:
            # [R8+disp8], retaining the x87 operation /digit.
            assert operand.disp in (0, 4, 8, 12, 16)
            encoded = bytes([0x41, encoded[0], 0x40 | (encoded[1] & 0x38), operand.disp])
        elif operand.base == capstone.x86.X86_REG_INVALID:
            # [R9+disp8] replaces the original absolute constant address.
            assert operand.disp in (0x4a6e8c, 0x4a6e90, 0x4a6e94)
            encoded = bytes([0x41, encoded[0], 0x41 | (encoded[1] & 0x38), operand.disp - 0x4a6e8c])
        else:
            assert operand.base in (capstone.x86.X86_REG_EAX, capstone.x86.X86_REG_ECX)
    body.append("    .byte " + ", ".join(f"0x{x:02x}" for x in encoded))

assembly = """// Generated by scripts/generate_vorbis_butterfly.py.
// Win64 ABI: RCX -> aligned guest FP state; RDX -> checked 176-byte scratch.
// Scratch: data[128], guest stack[20], constants[12], output EDX[4], padding.
.intel_syntax noprefix
.text
.globl wa2_vorbis_butterfly_native
.seh_proc wa2_vorbis_butterfly_native
wa2_vorbis_butterfly_native:
    mov r10, rcx
    mov r11, rdx
    sub rsp, 520
    .seh_stackalloc 520
    .seh_endprologue
    .byte 0x48, 0x0f, 0xae, 0x04, 0x24 // FXSAVE64 [RSP]
    .byte 0x49, 0x0f, 0xae, 0x0a       // FXRSTOR64 [R10]
    mov rax, r11
    lea r8, [r11 + 132]
    lea r9, [r11 + 148]
""" + "\n".join(body) + """
    mov DWORD PTR [r11 + 160], edx
    .byte 0x49, 0x0f, 0xae, 0x02       // FXSAVE64 [R10]
    .byte 0x48, 0x0f, 0xae, 0x0c, 0x24 // FXRSTOR64 [RSP]
    add rsp, 520
    ret
.seh_endproc
"""
(ROOT / "port/vorbis_butterfly.S").write_text(assembly)
signature = "// Generated by scripts/generate_vorbis_butterfly.py.\n"
signature += f"static constexpr unsigned butterfly_instructions = {len(instructions)};\n"
signature += "static constexpr std::uint8_t butterfly_code[] = {\n"
for n in range(0, len(code), 16):
    signature += "    " + ",".join(f"0x{x:02x}" for x in code[n:n + 16]) + ",\n"
signature += "};\n"
(ROOT / "port/vorbis_butterfly_signature.inc").write_text(signature)
print(f"Generated exact butterfly: {len(instructions)} instructions, {len(code)} bytes")
