"""Pin the statically compiled bitreader body to its original PE bytes."""
from pathlib import Path
import hashlib
import sys

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools/python"))
import capstone
import pefile

raw = (ROOT / "WA2_chs.exe").read_bytes()
assert hashlib.sha256(raw).hexdigest() == "246a263b965147a274fa59cdd7a72f6be10ba063d8cf4e61e74baefb56f29327"
pe = pefile.PE(data=raw)
start, end = 0x49fb20, 0x49fbc7
code = pe.get_data(start - pe.OPTIONAL_HEADER.ImageBase, end - start)
decoder = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
instructions = list(decoder.disasm(code, start))
assert sum(i.size for i in instructions) == len(code)
assert len(instructions) == 72 and instructions[-1].mnemonic == "ret"
signature = "// Generated by scripts/generate_bitreader_batch.py.\n"
signature += "static constexpr std::uint8_t bitreader_code[] = {\n"
for n in range(0, len(code), 16):
    signature += "    " + ",".join(f"0x{x:02x}" for x in code[n:n + 16]) + ",\n"
signature += "};\n"
(ROOT / "port/bitreader_signature.inc").write_text(signature)
print(f"Generated bitreader signature: {len(instructions)} static instructions, {len(code)} bytes")
