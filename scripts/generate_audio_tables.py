"""Record DirectSound COM slots from the pinned SDK headers."""
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parent.parent
source=(ROOT/'tools/python/ziglang/lib/libc/include/any-windows-any/dsound.h').read_text()
names={'unknown':None,'sound':'IDirectSound','sound8':'IDirectSound8','buffer':'IDirectSoundBuffer','buffer8':'IDirectSoundBuffer8','notify':'IDirectSoundNotify'}
out=['// Generated by scripts/generate_audio_tables.py from Zig 0.15.2 SDK headers.','struct Method {const char* name;unsigned arguments;};']
for key,name in names.items():
    methods=[('QueryInterface',3),('AddRef',1),('Release',1)]
    if name:
        body=re.search(r'#define INTERFACE '+name+r'\b.*?\n\{(.*?)\n\};',source,re.S).group(1);methods=[]
        for typed,plain,args in re.findall(r'STDMETHOD(?:_\([^,]+,\s*(\w+)\)|\((\w+)\))\((.*?)\)\s+PURE;',body,re.S):
            tail=re.sub(r'^THIS_?\s*','',args.strip()).strip();methods.append((typed or plain,1+(tail.count(',')+1 if tail else 0)))
    out.append('static constexpr Method methods_'+key+'[] = {')
    for i,(method,count) in enumerate(methods):out.append(f'    {{"{method}",{count}}}, // {i}')
    out.append('};');print(key,len(methods))
out+=['std::span<const Method> methods(Kind kind){switch(kind){']
for key in names:out.append(f'case Kind::{key}:return methods_{key};')
out+=['}throw std::runtime_error("DirectSound interface kind");}']
(ROOT/'port/audio_tables.inc').write_text('\n'.join(out)+'\n')
