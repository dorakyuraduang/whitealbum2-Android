"""Regenerate the fixed, SHA-bound x87 MDCT kernel (build-time only).

The floating-point opcodes are copied verbatim from the statically translated
image. In 64-bit mode their addressing bases use checked native scratch buffers.
No guest address reaches the native kernel and there is no runtime decoder.
"""
from pathlib import Path
import hashlib
import sys

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools/python"))
import capstone
import pefile

raw = (ROOT / "WA2_chs.exe").read_bytes()
assert hashlib.sha256(raw).hexdigest() == "246a263b965147a274fa59cdd7a72f6be10ba063d8cf4e61e74baefb56f29327"
pe = pefile.PE(data=raw)
start, end = 0x46ea23, 0x46eb14
code = pe.get_data(start - pe.OPTIONAL_HEADER.ImageBase, end - start)
decoder = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
instructions = list(decoder.disasm(code, start))
assert sum(i.size for i in instructions) == len(code)
body = []
for instruction in instructions:
    body.append(f"    // {instruction.address:#x}: {instruction.mnemonic} {instruction.op_str}")
    if 0xd8 <= instruction.bytes[0] <= 0xdf:
        body.append("    .byte " + ", ".join(f"0x{x:02x}" for x in instruction.bytes))
    elif instruction.address in (0x46ea53, 0x46ea8d, 0x46eac7, 0x46eb05):
        body.append("    add rdx, 8 // the next checked twiddle pair")
    elif instruction.address == 0x46eaea:
        body.append("    sub rax, 32")
    elif instruction.address == 0x46eaed:
        body.append("    sub rcx, 32")
    else:
        assert instruction.address in (0x46eb07, 0x46eb0e)
        body.append("    // Guest integer flags and branch are committed by the C++ wrapper.")

assembly = """// Generated by scripts/generate_vorbis_batch.py; do not change opcodes by hand.
// Win64 ABI: RCX -> aligned guest FXSAVE64 state; RDX -> 96 checked scratch bytes.
// Only volatile GPRs are used. The host x87, XMM and MXCSR state is restored.
.intel_syntax noprefix
.text
.globl wa2_vorbis_mdct_native
.seh_proc wa2_vorbis_mdct_native
wa2_vorbis_mdct_native:
    mov r10, rcx
    mov r11, rdx
    sub rsp, 520
    .seh_stackalloc 520
    .seh_endprologue
    .byte 0x48, 0x0f, 0xae, 0x04, 0x24 // FXSAVE64 [RSP]
    .byte 0x49, 0x0f, 0xae, 0x0a       // FXRSTOR64 [R10]
    mov rax, r11
    lea rcx, [r11 + 60]
    lea rdx, [r11 + 64]
""" + "\n".join(body) + """
    .byte 0x49, 0x0f, 0xae, 0x02       // FXSAVE64 [R10]
    .byte 0x48, 0x0f, 0xae, 0x0c, 0x24 // FXRSTOR64 [RSP]
    add rsp, 520
    ret
.seh_endproc
"""
(ROOT / "port/vorbis_batch.S").write_text(assembly)
signature = "// Generated by scripts/generate_vorbis_batch.py.\n"
signature += f"static constexpr unsigned mdct_instructions = {len(instructions)};\n"
signature += "static constexpr std::uint8_t mdct_code[] = {\n"
for n in range(0, len(code), 16):
    signature += "    " + ",".join(f"0x{x:02x}" for x in code[n:n + 16]) + ",\n"
signature += "};\n"
(ROOT / "port/vorbis_signature.inc").write_text(signature)
print(f"Generated exact MDCT kernel: {len(instructions)} guest instructions, {len(code)} signature bytes")
