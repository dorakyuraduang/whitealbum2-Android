"""Generate the exact whole sprite transform; build-time decoding only."""
from pathlib import Path
import hashlib
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'tools/python'))
import capstone
import pefile

raw = (ROOT / 'WA2_chs.exe').read_bytes()
assert hashlib.sha256(raw).hexdigest() == '246a263b965147a274fa59cdd7a72f6be10ba063d8cf4e61e74baefb56f29327'
pe = pefile.PE(data=raw)
decoder = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
decoder.detail = True
begin, end = 0x43bba8, 0x43bde0
code = pe.get_data(begin - pe.OPTIONAL_HEADER.ImageBase, end - begin)
instructions = list(decoder.disasm(code, begin))
assert sum(i.size for i in instructions) == len(code)
active = {i.address: i for i in instructions if i.address <= 0x43bdd7}

def costs(pc):
    if pc == end:
        return 0, 0
    ins = active[pc]
    targets = [ins.address + ins.size]
    if ins.mnemonic == 'jmp':
        targets = [ins.operands[0].imm]
    elif ins.mnemonic in ('je', 'jne'):
        targets.append(ins.operands[0].imm)
    bounds = [costs(target) for target in targets]
    return 1 + min(x[0] for x in bounds), 1 + max(x[1] for x in bounds)

minimum, maximum = costs(begin)
signature = ['// Generated by scripts/generate_sprite_transform.py.',
             'static constexpr std::uint8_t sprite_transform_code[]={' + ','.join(map(str, code)) + '};',
             f'static constexpr unsigned sprite_transform_minimum={minimum},sprite_transform_maximum={maximum};']
name = 'wa2_sprite_transform_native'
assembly = ['// Generated exact original x87 transform, checked scratch only.',
            '.intel_syntax noprefix', '.text', f'.globl {name}', f'.seh_proc {name}', f'{name}:',
            '    push rbx', '    .seh_pushreg rbx', '    push rsi', '    .seh_pushreg rsi',
            '    push rdi', '    .seh_pushreg rdi', '    sub rsp, 512', '    .seh_stackalloc 512',
            '    .seh_endprologue', '    mov r10, rcx', '    mov r11, rdx', '    mov r9, r8',
            '    .byte 0x48, 0x0f, 0xae, 0x04, 0x24 // FXSAVE64 [RSP]',
            '    .byte 0x49, 0x0f, 0xae, 0x0a // FXRSTOR64 [R10]']
registers = [('eax', 0), ('ecx', 4), ('edx', 8), ('ebx', 12), ('esi', 24), ('edi', 28)]
assembly += [f'    mov {reg}, DWORD PTR [r9+{offset}]' for reg, offset in registers]
assembly.append('    xor r8d, r8d')
for ins in active.values():
    assembly += [f'.L_transform_{ins.address:x}:', f'    // {ins.address:#x}: {ins.mnemonic} {ins.op_str}',
                 '    lea r8d, [r8d+1] // exact guest count without changing branch flags']
    if 0xd8 <= ins.bytes[0] <= 0xdf:
        if ins.bytes[1] >= 0xc0:
            encoded = ins.bytes
        else:
            operand = next(o for o in ins.operands if o.type == capstone.x86.X86_OP_MEM)
            assert operand.mem.index == 0
            if operand.mem.base == capstone.x86.X86_REG_ESP:
                displacement = operand.mem.disp
                assert 0 <= displacement <= 0x9c
            else:
                assert operand.mem.base == capstone.x86.X86_REG_ESI
                displacement = 0xa0 + operand.mem.disp
                assert 0xa0 <= displacement <= 0x164
            encoded = bytes([0x41, ins.bytes[0], 0x83 | (ins.bytes[1] & 0x38)]) + displacement.to_bytes(4, 'little')
        assembly.append('    .byte ' + ', '.join(f'0x{x:02x}' for x in encoded))
    elif ins.mnemonic in ('je', 'jne', 'jmp'):
        target = ins.operands[0].imm
        assert target == end or target in active
        assembly.append(f'    {ins.mnemonic} .L_transform_{target:x}')
    elif ins.mnemonic == 'lea':
        assert ins.op_str == 'ecx, [esi + 0x53]'
        assembly.append('    lea ecx, [rsi+0x53]')
    else:
        assert ins.mnemonic in ('mov', 'movsx', 'movzx', 'and', 'xor', 'test', 'add')
        operands = ins.op_str
        for operand in ins.operands:
            if operand.type != capstone.x86.X86_OP_MEM:
                continue
            assert operand.mem.index == 0
            if operand.mem.base == capstone.x86.X86_REG_ESP:
                offset = operand.mem.disp
            elif operand.mem.base == capstone.x86.X86_REG_ESI:
                offset = 0xa0 + operand.mem.disp
            else:
                assert ins.address == 0x43bd7d and operand.mem.base == capstone.x86.X86_REG_EAX
                offset = 0x168
            operands = re.sub(r'\[[^\]]+\]', f'[r11+{offset}]', operands)
        assembly.append(f'    {ins.mnemonic} {operands}')
assembly.append(f'.L_transform_{end:x}:')
assembly += [f'    mov DWORD PTR [r9+{offset}], {reg}' for reg, offset in registers]
assembly += ['    mov DWORD PTR [r9+32], r8d',
             '    .byte 0x49, 0x0f, 0xae, 0x02 // FXSAVE64 [R10]',
             '    .byte 0x48, 0x0f, 0xae, 0x0c, 0x24 // FXRSTOR64 [RSP]',
             '    add rsp, 512', '    pop rdi', '    pop rsi', '    pop rbx', '    ret', '.seh_endproc']
(ROOT / 'port/sprite_transform.S').write_text('\n'.join(assembly) + '\n')
(ROOT / 'port/sprite_transform_signature.inc').write_text('\n'.join(signature) + '\n')
print(f'Generated exact whole sprite transform: {minimum}..{maximum} instructions per call')
