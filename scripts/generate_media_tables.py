"""Record DirectShow COM slots and x86 stack widths from pinned SDK headers."""
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parent.parent
SDK=ROOT/'tools/python/ziglang/lib/libc/include/any-windows-any'
source=(SDK/'strmif.h').read_text()+'\n'+(SDK/'control.h').read_text()
names={'unknown':None,'graph':'IGraphBuilder','filter_graph':'IFilterGraph','control':'IMediaControl','event':'IMediaEvent','event_ex':'IMediaEventEx','audio':'IBasicAudio','video_window':'IVideoWindow','basic_video':'IBasicVideo','seeking':'IMediaSeeking','position':'IMediaPosition'}
out=['// Generated by scripts/generate_media_tables.py from Zig 0.15.2 SDK headers.','struct Method {const char* name;unsigned arguments;};']
for key,name in names.items():
    methods=[('QueryInterface',3),('AddRef',1),('Release',1)]
    if name:
        body=re.search(r'typedef struct '+name+r'Vtbl\s*\{(.*?)\}\s*'+name+r'Vtbl;',source,re.S).group(1);methods=[]
        for method,args in re.findall(r'\((?:STDMETHODCALLTYPE|WINAPI)\s*\*(\w+)\)\s*\((.*?)\)\s*;',body,re.S):
            fields=args.split(',');count=len(fields)
            for field in fields:
                if re.search(r'\b(?:double|DOUBLE|REFTIME|LONGLONG|REFERENCE_TIME)\s+\w+\s*$',field) and '*' not in field:count+=1
            methods.append((method,count))
    if len(methods)<3:raise ValueError(name)
    out.append('static constexpr Method methods_'+key+'[] = {')
    for i,(method,count) in enumerate(methods):out.append(f'    {{"{method}",{count}}}, // {i}')
    out.append('};');print(key,len(methods))
out+=['std::span<const Method> methods(Kind kind){switch(kind){']
for key in names:out.append(f'case Kind::{key}:return methods_{key};')
out+=['}throw std::runtime_error("DirectShow interface kind");}']
(ROOT/'port/media_tables.inc').write_text('\n'.join(out)+'\n')
