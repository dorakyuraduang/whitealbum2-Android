"""Generate checked COM slot names/argument counts from the pinned SDK headers."""
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parent.parent
SDK=ROOT/'tools/python/ziglang/lib/libc/include/any-windows-any'
names={'unknown':None,'d3d':'IDirect3D9','device':'IDirect3DDevice9','texture':'IDirect3DTexture9','surface':'IDirect3DSurface9','vertexbuffer':'IDirect3DVertexBuffer9','indexbuffer':'IDirect3DIndexBuffer9','vertexshader':'IDirect3DVertexShader9','pixelshader':'IDirect3DPixelShader9','declaration':'IDirect3DVertexDeclaration9','stateblock':'IDirect3DStateBlock9','swapchain':'IDirect3DSwapChain9','buffer':'ID3DXBuffer','base_texture':'IDirect3DBaseTexture9','resource':'IDirect3DResource9'}
source=(SDK/'d3d9.h').read_text()+'\n'+(SDK/'d3dx9core.h').read_text()
out=['// Generated by scripts/generate_d3d9_tables.py from Zig 0.15.2 SDK headers.', 'struct Method {const char* name;unsigned arguments;};']
for key,name in names.items():
    if name:
        body=re.search(r'#define INTERFACE '+name+r'\b.*?\n\{(.*?)\n\};',source,re.S).group(1)
        methods=[]
        for typed,plain,args in re.findall(r'STDMETHOD(?:_\([^,]+,\s*(\w+)\)|\((\w+)\))\((.*?)\)\s+PURE;',body,re.S):
            args=args.strip();tail=re.sub(r'^THIS_?\s*','',args).strip()
            methods.append((typed or plain,1+(tail.count(',')+1 if tail else 0)))
    else:methods=[('QueryInterface',3),('AddRef',1),('Release',1)]
    if len(methods)<3:raise ValueError(name)
    out.append('static constexpr Method methods_'+key+'[] = {')
    for i,(method,count) in enumerate(methods):out.append(f'    {{"{method}",{count}}}, // {i}')
    out.append('};')
    print(key,len(methods))
out+=['std::span<const Method> methods(Kind kind){switch(kind){']
for key in names:out.append(f'case Kind::{key}:return methods_{key};')
out+=['}throw std::runtime_error("D3D interface kind");}']
(ROOT/'port/d3d9_tables.inc').write_text('\n'.join(out)+'\n')
