"""Build-time-only exact x87 UV kernels; no runtime decoder or guest pointer."""
from pathlib import Path
import hashlib
import sys

ROOT=Path(__file__).resolve().parent.parent
sys.path.insert(0,str(ROOT/'tools/python'))
import capstone
import pefile

raw=(ROOT/'WA2_chs.exe').read_bytes()
assert hashlib.sha256(raw).hexdigest()=='246a263b965147a274fa59cdd7a72f6be10ba063d8cf4e61e74baefb56f29327'
pe=pefile.PE(data=raw)
decoder=capstone.Cs(capstone.CS_ARCH_X86,capstone.CS_MODE_32)
decoder.detail=True
assembly=['// Generated by scripts/generate_uv_batch.py. Exact original x87 opcodes,',
          '// checked scratch operands, one iteration, host FP state preserved.',
          '.intel_syntax noprefix','.text']
signature=['// Generated by scripts/generate_uv_batch.py.']
for axis,begin,end,last in [('x',0x43cc4d,0x43cd06,0x43ccfd),('y',0x43cd37,0x43cdf0,0x43cde7)]:
    ranges=[(begin,end)]+([(0x43d77d,0x43d78c)] if axis=='y' else [])
    instructions=[]
    for number,(start,stop) in enumerate(ranges):
        code=pe.get_data(start-pe.OPTIONAL_HEADER.ImageBase,stop-start)
        decoded=list(decoder.disasm(code,start))
        assert sum(i.size for i in decoded)==len(code)
        instructions+=decoded
        signature.append(f'static constexpr std::uint8_t uv_{axis}_{number}_code[]={{'+','.join(map(str,code))+'};')
    name=f'wa2_uv_{axis}_native'
    assembly += [f'.globl {name}',f'.seh_proc {name}',f'{name}:',
        '    mov r10, rcx','    mov r11, rdx','    mov r9, r8','    sub rsp, 520',
        '    .seh_stackalloc 520','    .seh_endprologue',
        '    .byte 0x48, 0x0f, 0xae, 0x04, 0x24 // FXSAVE64 [RSP]',
        '    .byte 0x49, 0x0f, 0xae, 0x0a // FXRSTOR64 [R10]',
        '    mov eax, DWORD PTR [r9]','    mov edx, DWORD PTR [r9+4]','    xor r8d, r8d']
    offsets={0x30:0,0x10:4,0x1c:8,0x68:12,0x6c:16,
             (0x268 if axis=='x' else 0x340):20,(0x2f8 if axis=='x' else 0x2b0):24}
    for ins in instructions:
        assembly += [f'.L_uv_{axis}_{ins.address:x}:',f'    // {ins.address:#x}: {ins.mnemonic} {ins.op_str}']
        if ins.address==last:
            assembly += ['    lea r8d, [r8d+3] // INC, CMP and JL committed in C++',f'    jmp .L_uv_{axis}_finish']
            continue
        if last<ins.address<end:continue
        assembly.append('    lea r8d, [r8d+1] // exact dynamic guest cost; preserves flags')
        if 0xd8<=ins.bytes[0]<=0xdf:
            if ins.bytes[1]>=0xc0:
                encoded=ins.bytes
            else:
                operand=next(o for o in ins.operands if o.type==capstone.x86.X86_OP_MEM)
                assert operand.mem.base==capstone.x86.X86_REG_ESP
                assert operand.mem.index in (0,capstone.x86.X86_REG_ECX)
                displacement=offsets[operand.mem.disp]
                encoded=bytes([0x41,ins.bytes[0],0x43|(ins.bytes[1]&0x38),displacement])
            assembly.append('    .byte '+', '.join(f'0x{x:02x}' for x in encoded))
        elif ins.mnemonic=='test':
            assert ins.op_str in ('ah, 5','ah, 0x41')
            assembly.append('    test '+ins.op_str)
        elif ins.mnemonic=='add':
            assert ins.op_str=='dword ptr [esp + 0x30], edx'
            assembly.append('    add DWORD PTR [r11], edx')
        elif ins.mnemonic in ('jp','jne','jmp'):
            target=ins.operands[0].imm
            assert any(i.address==target for i in instructions)
            assembly.append(f'    {ins.mnemonic} .L_uv_{axis}_{target:x}')
        else:raise AssertionError((hex(ins.address),ins.mnemonic,ins.op_str))
    assembly += [f'.L_uv_{axis}_finish:',
        '    mov DWORD PTR [r9], eax','    mov DWORD PTR [r9+8], r8d',
        '    .byte 0x49, 0x0f, 0xae, 0x02 // FXSAVE64 [R10]',
        '    .byte 0x48, 0x0f, 0xae, 0x0c, 0x24 // FXRSTOR64 [RSP]',
        '    add rsp, 520','    ret','.seh_endproc']
(ROOT/'port/uv_batch.S').write_text('\n'.join(assembly)+'\n')
(ROOT/'port/uv_signature.inc').write_text('\n'.join(signature)+'\n')
print('Generated both exact x87 UV iterations with dynamic branch counts')
